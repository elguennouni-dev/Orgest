-- Devis (cotations) : proposition de prix à un client, convertible en vente.
CREATE TABLE quote (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id        BIGINT        NOT NULL REFERENCES app_user(id),
    number         VARCHAR(20)   NOT NULL,
    status         VARCHAR(12)   NOT NULL DEFAULT 'DRAFT',
    customer_name  VARCHAR(120),
    customer_phone VARCHAR(30),
    note           VARCHAR(500),
    valid_until    DATE          NOT NULL,
    subtotal       NUMERIC(14,2) NOT NULL,
    sale_id        BIGINT REFERENCES sale(id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_quote_number UNIQUE (shop_id, number)
);
CREATE INDEX ix_quote_shop_date ON quote (shop_id, created_at);
CREATE INDEX ix_quote_shop_status ON quote (shop_id, status);

CREATE TABLE quote_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id        BIGINT        NOT NULL REFERENCES quote(id) ON DELETE CASCADE,
    item_id         BIGINT REFERENCES item(id),
    description     VARCHAR(160)  NOT NULL,
    karat           INTEGER       NOT NULL,
    weight_g        NUMERIC(10,3) NOT NULL,
    quantity        INTEGER       NOT NULL DEFAULT 1,
    price_per_gram  NUMERIC(12,2) NOT NULL,
    making_per_gram NUMERIC(10,2) NOT NULL,
    line_total      NUMERIC(14,2) NOT NULL
);
CREATE INDEX ix_quote_line_quote ON quote_line (quote_id);
