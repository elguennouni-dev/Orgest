CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id    BIGINT       NOT NULL REFERENCES app_user(id),
    name       VARCHAR(120) NOT NULL,
    phone      VARCHAR(30),
    note       VARCHAR(500),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_customer_shop_name ON customer (shop_id, lower(name));
CREATE INDEX ix_customer_shop_phone ON customer (shop_id, phone);

ALTER TABLE sale ADD COLUMN customer_id BIGINT REFERENCES customer(id);
ALTER TABLE sale ADD COLUMN credit_due NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (credit_due >= 0);
CREATE INDEX ix_sale_customer ON sale (shop_id, customer_id);

CREATE TABLE customer_payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id     BIGINT        NOT NULL REFERENCES app_user(id),
    customer_id BIGINT        NOT NULL REFERENCES customer(id),
    sale_id     BIGINT        NOT NULL REFERENCES sale(id),
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    method      VARCHAR(10)   NOT NULL,
    note        VARCHAR(255),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_cpay_customer ON customer_payment (shop_id, customer_id, created_at);
