CREATE TABLE blog_post (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(120) NOT NULL,
    title            VARCHAR(160) NOT NULL,
    excerpt          VARCHAR(300),
    content          TEXT         NOT NULL,
    category         VARCHAR(60),
    cover            VARCHAR(60),
    cover_alt        VARCHAR(160),
    meta_title       VARCHAR(70),
    meta_description VARCHAR(170),
    keywords         VARCHAR(200),
    read_minutes     INT          NOT NULL DEFAULT 3 CHECK (read_minutes BETWEEN 1 AND 60),
    published        BOOLEAN      NOT NULL DEFAULT FALSE,
    published_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_blog_slug UNIQUE (slug)
);
CREATE INDEX idx_blog_published ON blog_post (published, published_at DESC);
