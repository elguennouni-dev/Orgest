CREATE TABLE app_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(60)  NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    role             VARCHAR(10)  NOT NULL CHECK (role IN ('ADMIN','SHOP')),
    shop_name        VARCHAR(120),
    owner_name       VARCHAR(120),
    phone            VARCHAR(30),
    city             VARCHAR(80),
    address          VARCHAR(255),
    ice              VARCHAR(30),
    receipt_footer   VARCHAR(255),
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    subscription_end DATE,
    token_version    INTEGER      NOT NULL DEFAULT 0,
    failed_attempts  INTEGER      NOT NULL DEFAULT 0,
    locked_until     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_user_username ON app_user (lower(username));

CREATE TABLE payment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id      BIGINT        NOT NULL REFERENCES app_user(id),
    amount       NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    method       VARCHAR(20)   NOT NULL,
    months       INTEGER       NOT NULL CHECK (months > 0),
    reference    VARCHAR(80),
    note         VARCHAR(255),
    period_start DATE          NOT NULL,
    period_end   DATE          NOT NULL,
    paid_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_payment_shop ON payment (shop_id);

CREATE TABLE gold_price (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id       BIGINT        NOT NULL REFERENCES app_user(id),
    karat         INTEGER       NOT NULL CHECK (karat IN (18,21,24)),
    sell_per_gram NUMERIC(12,2) NOT NULL CHECK (sell_per_gram >= 0),
    buy_per_gram  NUMERIC(12,2) NOT NULL CHECK (buy_per_gram >= 0),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (shop_id, karat)
);

CREATE TABLE shop_counter (
    shop_id BIGINT      NOT NULL REFERENCES app_user(id),
    kind    VARCHAR(10) NOT NULL,
    value   BIGINT      NOT NULL,
    PRIMARY KEY (shop_id, kind)
);

CREATE TABLE item (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id           BIGINT        NOT NULL REFERENCES app_user(id),
    ref               VARCHAR(20)   NOT NULL,
    name              VARCHAR(120)  NOT NULL,
    category          VARCHAR(30)   NOT NULL,
    karat             INTEGER       NOT NULL CHECK (karat IN (18,21,24)),
    weight_g          NUMERIC(10,3) NOT NULL CHECK (weight_g > 0),
    making_per_gram   NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (making_per_gram >= 0),
    status            VARCHAR(12)   NOT NULL DEFAULT 'IN_STOCK',
    photo_file        VARCHAR(60),
    note              VARCHAR(500),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (shop_id, ref)
);
CREATE INDEX ix_item_shop_status ON item (shop_id, status);

CREATE TABLE buyback (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id        BIGINT        NOT NULL REFERENCES app_user(id),
    number         VARCHAR(20)   NOT NULL,
    customer_name  VARCHAR(120),
    customer_phone VARCHAR(30),
    customer_cin   VARCHAR(20),
    description    VARCHAR(255),
    karat          INTEGER       NOT NULL CHECK (karat IN (18,21,24)),
    gross_weight_g NUMERIC(10,3) NOT NULL CHECK (gross_weight_g > 0),
    deduction_pct  NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (deduction_pct >= 0 AND deduction_pct < 100),
    net_weight_g   NUMERIC(10,3) NOT NULL,
    price_per_gram NUMERIC(12,2) NOT NULL CHECK (price_per_gram >= 0),
    total          NUMERIC(14,2) NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (shop_id, number)
);
CREATE INDEX ix_buyback_shop_date ON buyback (shop_id, created_at);

CREATE TABLE sale (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id          BIGINT        NOT NULL REFERENCES app_user(id),
    number           VARCHAR(20)   NOT NULL,
    type             VARCHAR(10)   NOT NULL CHECK (type IN ('SALE','EXCHANGE')),
    customer_name    VARCHAR(120),
    customer_phone   VARCHAR(30),
    subtotal         NUMERIC(14,2) NOT NULL,
    trade_in_amount  NUMERIC(14,2) NOT NULL DEFAULT 0,
    buyback_id       BIGINT REFERENCES buyback(id),
    balance          NUMERIC(14,2) NOT NULL,
    payment_mode     VARCHAR(12)   NOT NULL CHECK (payment_mode IN ('CASH','INSTALLMENT')),
    down_payment     NUMERIC(14,2) NOT NULL DEFAULT 0,
    months           INTEGER       NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (shop_id, number)
);
CREATE INDEX ix_sale_shop_date ON sale (shop_id, created_at);

CREATE TABLE sale_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id         BIGINT        NOT NULL REFERENCES sale(id) ON DELETE CASCADE,
    item_id         BIGINT REFERENCES item(id),
    description     VARCHAR(160)  NOT NULL,
    karat           INTEGER       NOT NULL,
    weight_g        NUMERIC(10,3) NOT NULL,
    price_per_gram  NUMERIC(12,2) NOT NULL,
    making_per_gram NUMERIC(10,2) NOT NULL,
    line_total      NUMERIC(14,2) NOT NULL
);
CREATE INDEX ix_sale_line_sale ON sale_line (sale_id);

CREATE TABLE installment (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id  BIGINT        NOT NULL REFERENCES sale(id) ON DELETE CASCADE,
    shop_id  BIGINT        NOT NULL REFERENCES app_user(id),
    seq      INTEGER       NOT NULL,
    due_date DATE          NOT NULL,
    amount   NUMERIC(14,2) NOT NULL,
    paid     BOOLEAN       NOT NULL DEFAULT FALSE,
    paid_at  TIMESTAMPTZ
);
CREATE INDEX ix_installment_shop_due ON installment (shop_id, paid, due_date);

CREATE TABLE workshop_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id           BIGINT        NOT NULL REFERENCES app_user(id),
    number            VARCHAR(20)   NOT NULL,
    customer_name     VARCHAR(120),
    customer_phone    VARCHAR(30),
    description       VARCHAR(255)  NOT NULL,
    karat             INTEGER       NOT NULL CHECK (karat IN (18,21,24)),
    artisan_name      VARCHAR(120)  NOT NULL,
    artisan_phone     VARCHAR(30),
    given_weight_g    NUMERIC(10,3) NOT NULL DEFAULT 0,
    received_weight_g NUMERIC(10,3),
    labour_cost       NUMERIC(14,2) NOT NULL DEFAULT 0,
    deposit_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    agreed_price      NUMERIC(14,2) NOT NULL DEFAULT 0,
    due_date          DATE,
    status            VARCHAR(12)   NOT NULL DEFAULT 'SENT',
    note              VARCHAR(500),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (shop_id, number)
);
CREATE INDEX ix_workshop_shop_status ON workshop_order (shop_id, status);

CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT,
    username   VARCHAR(60),
    action     VARCHAR(40)  NOT NULL,
    detail     VARCHAR(500),
    ip         VARCHAR(45),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_created ON audit_log (created_at);
